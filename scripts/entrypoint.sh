#!/bin/bash
# Entrypoint of the php-fpm container: size the pool from the container memory limit (K1), write the
# pool configuration from environment variables and run php-fpm in the foreground. Any other command
# (CronJobs, "docker run <image> bash") is executed as given.
set -euo pipefail

log() { printf '[entrypoint] %s\n' "$*" >&2; }

if (( $# > 0 )) && [[ "$1" != "php-fpm" ]]; then
    exec "$@"
fi

# ---- DOCUMENT_ROOT without trailing slash (same normalisation as the Apache container)
if [[ "${DOCUMENT_ROOT:-}" != "/" ]]; then
    export DOCUMENT_ROOT="${DOCUMENT_ROOT%/}"
fi

# ---- container memory limit in MiB (cgroup v2, then v1); empty when unlimited or unknown
cgroup_limit_mib() {
    local raw=""
    if [[ -r /sys/fs/cgroup/memory.max ]]; then
        raw=$(< /sys/fs/cgroup/memory.max)
    elif [[ -r /sys/fs/cgroup/memory/memory.limit_in_bytes ]]; then
        raw=$(< /sys/fs/cgroup/memory/memory.limit_in_bytes)
    fi
    if [[ "$raw" =~ ^[0-9]+$ ]] && (( raw < (1 << 50) )); then
        echo $(( raw / 1024 / 1024 ))
    fi
}

if [[ -z "${PHP_FPM_MAX_CHILDREN:-}" ]]; then
    limit_mib=$(cgroup_limit_mib)
    if [[ -n "$limit_mib" ]]; then
        children=$(( (limit_mib - PHP_FPM_BASELINE_MEMORY_MB) / PHP_FPM_CHILD_MEMORY_MB ))
        (( children < 2 )) && children=2
        log "memory limit ${limit_mib} MiB, baseline ${PHP_FPM_BASELINE_MEMORY_MB} MiB, ${PHP_FPM_CHILD_MEMORY_MB} MiB per child -> pm.max_children=${children}"
    else
        children=10
        log "no container memory limit found -> pm.max_children=${children} (fallback)"
    fi
    PHP_FPM_MAX_CHILDREN=$children
else
    log "pm.max_children=${PHP_FPM_MAX_CHILDREN} (set explicitly)"
fi

# ---- dynamic pm: min_spare <= start <= max_spare <= max_children, otherwise php-fpm refuses to start
max_spare=$PHP_FPM_MAX_SPARE_SERVERS
(( max_spare > PHP_FPM_MAX_CHILDREN )) && max_spare=$PHP_FPM_MAX_CHILDREN
min_spare=$PHP_FPM_MIN_SPARE_SERVERS
(( min_spare > max_spare )) && min_spare=$max_spare
(( min_spare < 1 )) && min_spare=1
start=$PHP_FPM_START_SERVERS
(( start < min_spare )) && start=$min_spare
(( start > max_spare )) && start=$max_spare

cat > /usr/local/etc/php-fpm.d/zz-propeller.conf <<POOL
; generated by entrypoint.sh from the environment at container start
[www]
user = propeller
group = propeller
listen = ${PHP_FPM_LISTEN}
listen.allowed_clients = 127.0.0.1
pm = ${PHP_FPM_PM}
pm.max_children = ${PHP_FPM_MAX_CHILDREN}
pm.start_servers = ${start}
pm.min_spare_servers = ${min_spare}
pm.max_spare_servers = ${max_spare}
pm.process_idle_timeout = ${PHP_FPM_PROCESS_IDLE_TIMEOUT}
; recycle children: bounds memory growth of long-lived PHP processes
pm.max_requests = ${PHP_FPM_MAX_REQUESTS}
; probes and metrics, only reachable through the Apache container (see 000-default.conf)
pm.status_path = /fpm-status
ping.path = /fpm-ping
ping.response = pong
; wall-clock bound per request: max_execution_time only counts CPU time, a worker stuck on NFS or MySQL
; would otherwise never be freed (H4)
request_terminate_timeout = ${PHP_FPM_REQUEST_TERMINATE_TIMEOUT}
request_slowlog_timeout = ${PHP_FPM_SLOWLOG_TIMEOUT}
slowlog = /proc/self/fd/2
; PHP sees the container environment (DB credentials, DOCUMENT_ROOT, ...) exactly like it did with mod_php
clear_env = no
catch_workers_output = yes
decorate_workers_output = no
POOL

if (( $# > 0 )); then
    exec "$@"
fi
exec php-fpm -F
